/*
 * Builds src/json/potential-values.json from the game's own master data
 * (rsdnt_equip.arc :: tuning/xml/equip/potentialValue), extracted with
 * tools-js/xfs-parse.cjs.
 *
 * "Plus value" (プラス値) is the weapon/armour `potential` field: it raises the
 * weapon's damage multiplier (the game caps its effect at 20 or 25 depending on
 * the piece). It is raised with `box/equipment/potentialupmaterial` (plus-up
 * materials) or `box/equipment/potentialup` (fodder equipment).
 *
 * The table has one row per rarity:
 *   mRarity            rarity (1..10)
 *   mStrengthBasePrice zeny base
 *   mMaxPlusValue      the cap for that rarity (the client prints "limit value")
 *   mUpValueList       [equipment value, material value]
 *
 * sPlayer::getEquipPotentialValue(rarity, count, kind) returns
 * mUpValueList[kind] * count, which is where the two values come from.
 *
 * Run: node tools-js/costruisci-potential-values.cjs
 */
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');

const ROOT = path.join(__dirname, '..');
const ARC = path.join(__dirname, 'rsdnt_equip.arc');
const PROP_ARC = path.join(__dirname, 'rsdnt_property.arc');
const OUT = path.join(ROOT, 'src/json/potential-values.json');
const TABLE = 'potentialValue';
const PLUSUP_TABLE = 'item_plusup_material';
const KEY = 'kaseoa nkaeka;eawf3';

function unscramble(buf) {
  const out = Buffer.alloc(buf.length);
  for (let i = 0; i + 3 < buf.length; i += 4) {
    out[i] = buf[i + 3];
    out[i + 1] = buf[i + 2];
    out[i + 2] = buf[i + 1];
    out[i + 3] = buf[i];
  }
  const rest = buf.length % 4;
  if (rest > 0) buf.copy(out, buf.length - rest, buf.length - rest);
  return out;
}

function decode(buf) {
  const { Blowfish } = require('egoroof-blowfish');
  const bf = new Blowfish(KEY, Blowfish.MODE.ECB, Blowfish.PADDING.NULL);
  const scrambled = unscramble(buf);
  let plain = Buffer.from(bf.decode(scrambled, Blowfish.TYPE.UINT8_ARRAY));
  if (plain.length < scrambled.length) {
    plain = Buffer.concat([plain, Buffer.alloc(scrambled.length - plain.length)]);
  }
  return unscramble(plain);
}

function readTable(archivePath, wanted) {
  const { parseXfs } = require('./xfs-parse.cjs');
  const raw = fs.readFileSync(archivePath);
  const encrypted = raw.toString('ascii', 0, 4) === 'ARCC';
  const body = encrypted ? decode(raw.subarray(8)) : raw.subarray(8);
  const count = raw.readUInt16LE(6);
  for (let i = 0; i < count; i++) {
    const entry = i * 80;
    const name = body.subarray(entry, entry + 64).toString('utf8').replace(/\0.*$/, '').split('\\').pop();
    if (name !== wanted) continue;
    const size = body.readUInt32LE(entry + 68);
    const start = body.readUInt32LE(entry + 76) - 8;
    return parseXfs(zlib.inflateSync(body.subarray(start, start + size)));
  }
  throw new Error(`${wanted} not found in ${path.basename(archivePath)}`);
}

function main() {
  const rows = readTable(ARC, TABLE).root.mDataList.mpArray;
  const byRarity = {};
  for (const row of rows) {
    byRarity[String(row.mRarity)] = {
      prezzoBase: Number(row.mStrengthBasePrice ?? 0),
      maxPlus: Number(row.mMaxPlusValue ?? 0),
      // [0] = value of one fodder equipment, [1] = value of one plus-up material.
      upValue: (row.mUpValueList ?? []).map(Number),
    };
  }

  // The only materials the client lets you feed into a weapon. Ids, rarity and
  // zeny come from the game; the condition (which weapon types they work on) is
  // checked by the client.
  const materials = {};
  for (const row of readTable(PROP_ARC, PLUSUP_TABLE).root.mDataList.mpArray) {
    materials[String(row.mItemID)] = {
      rarita: Number(row.mRarity ?? 0),
      zeny: Number(row.mZeny ?? 0),
      condizione: Number(row.mConditionID ?? 0),
    };
  }

  const out = {
    _comment:
      'Generated by tools-js/costruisci-potential-values.cjs from the game master data ' +
      '(rsdnt_equip.arc :: tuning/xml/equip/potentialValue, ' +
      'rsdnt_property.arc :: tuning/xml/item/item_plusup_material). Do not edit by hand.',
    _source: { potentials: TABLE, materials: PLUSUP_TABLE },
    byRarity,
    materials,
  };
  fs.writeFileSync(OUT, JSON.stringify(out, null, 1));
  console.log(
    `scritto ${path.relative(ROOT, OUT)}: ${rows.length} rarita', ${Object.keys(materials).length} materiali plus`,
  );
}

main();
