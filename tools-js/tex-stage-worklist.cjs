// Stage the textures worth translating next into a flat, Photoshop-friendly
// working folder.
//
//   node tools-js/tex-stage-worklist.cjs --tier 1 --out dump/to-restore
//   node tools-js/tex-stage-worklist.cjs --tier 2 --tier 3 --out dump/to-restore
//
// For each matching manifest row it copies:
//   <out>/tex/<flat>.tex   the pristine texture, needed as the header source by
//                          tex_android.py encode -- keep this untouched
//   <out>/png/<flat>.png   the decoded, editable version
// and writes <out>/worklist.csv mapping flat name -> pack + arc + entry name, so
// the edited files can be put back.
//
// Selection: tier in --tier, jpn==1 (baked Japanese text), decodable==1 (local
// RGBA4/RGBA8/R5G6B5), status != duplicate (duplicates are the same art already
// staged under another name).
const fs = require('fs');
const path = require('path');

const argv = process.argv.slice(2);
// accept both "--name=value" and "--name value"
const argAll = (name) => {
  const out = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith(`--${name}=`)) out.push(a.slice(name.length + 3));
    else if (a === `--${name}` && argv[i + 1] && !argv[i + 1].startsWith('--')) out.push(argv[++i]);
  }
  return out;
};
const arg = (name, dflt) => argAll(name)[0] ?? dflt;

const DUMP = arg('dump', 'dump');
const TIERS = argAll('tier').flatMap((t) => t.split(',')).map(Number).filter(Boolean);
const OUT = arg('out', 'dump/to-restore');
const INCLUDE_BLOCKED = argv.includes('--with-blocked');

if (!TIERS.length) {
  console.error('uso: node tex-stage-worklist.cjs --tier 1 [--tier 2 ...] [--out dump/to-restore]');
  process.exit(1);
}

const manifest = path.join(DUMP, 'manifest.json');
if (!fs.existsSync(manifest)) {
  console.error(`${manifest} not found -- run tools-js/gui-tex-dump.cjs first`);
  process.exit(1);
}
const records = JSON.parse(fs.readFileSync(manifest));

const pick = records.filter(
  (r) =>
    TIERS.includes(r.tier) &&
    r.status !== 'duplicate' &&
    (INCLUDE_BLOCKED || r.decodable === 1) &&
    (INCLUDE_BLOCKED || r.jpn === 1)
);

if (!pick.length) {
  console.error(`nothing matches tiers ${TIERS.join(',')}`);
  process.exit(1);
}

// flat, unique, readable names: <pack>_<arc-basename>_<texture-basename>
function flatName(r) {
  const arcBase = path.basename(r.arc).replace(/\.arc$/i, '');
  const entryBase = r.entry.split('/').pop();
  return `${r.pack}_${arcBase}_${entryBase}`;
}

const used = new Map();
const rows = [];
let missingTex = 0;
let missingPng = 0;

// manifest tex_path is already repo-relative (e.g. dump/tex/GUI.00/.../X.tex);
// the PNG sits in the mirrored png/ tree.
for (const r of pick) {
  const texReal = path.resolve(r.tex_path);
  const png = texReal.replace(`${path.sep}tex${path.sep}`, `${path.sep}png${path.sep}`).replace(/\.tex$/, '.png');

  if (!fs.existsSync(texReal) || !fs.statSync(texReal).isFile()) {
    missingTex++;
    continue;
  }
  if (!fs.existsSync(png)) {
    missingPng++;
    continue;
  }

  let flat = flatName(r);
  if (used.has(flat)) {
    used.set(flat, used.get(flat) + 1);
    flat = `${flat}~${used.get(flat)}`;
  } else {
    used.set(flat, 1);
  }

  const texOut = path.join(OUT, 'tex', `${flat}.tex`);
  const pngOut = path.join(OUT, 'png', `${flat}.png`);
  fs.mkdirSync(path.dirname(texOut), { recursive: true });
  fs.mkdirSync(path.dirname(pngOut), { recursive: true });
  fs.copyFileSync(texReal, texOut);
  fs.copyFileSync(png, pngOut);

  rows.push({
    flat,
    tier: r.tier,
    pack: r.pack,
    arc: r.arc,
    entry: r.entry,
    format: r.format,
    type: r.type,
    width: r.width,
    height: r.height,
    size: r.size,
    tex: path.relative(OUT, texOut),
    png: path.relative(OUT, pngOut),
  });
}

// ---------------------------------------------------------------------------
const cols = ['flat', 'tier', 'pack', 'arc', 'entry', 'format', 'type', 'width', 'height', 'size', 'tex', 'png'];
const csv = [
  cols.join(','),
  ...rows.map((r) =>
    cols
      .map((c) => {
        const v = String(r[c] ?? '');
        return /[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v;
      })
      .join(',')
  ),
].join('\n');
fs.writeFileSync(path.join(OUT, 'worklist.csv'), csv + '\n');

// grouped summary for the README
const byArc = {};
for (const r of rows) (byArc[r.arc] = byArc[r.arc] || []).push(r);
const arcs = Object.entries(byArc).sort((a, b) => b[1].length - a[1].length);

const totalBytes = rows.reduce((a, r) => a + r.size, 0);
const byTier = {};
for (const r of rows) byTier[r.tier] = (byTier[r.tier] || 0) + 1;

const readme = [
  `# Translation worklist — tier ${TIERS.join(' + ')}`,
  '',
  `Generated by \`tools-js/tex-stage-worklist.cjs --tier ${TIERS.join(' --tier ')}\` from \`${manifest}\`.`,
  '',
  `${rows.length} textures, ${(totalBytes / 1048576).toFixed(1)} MiB, all in \`${[...new Set(rows.map((r) => r.pack))].join(', ')}\`.`,
  `By tier: ${Object.entries(byTier).sort().map(([k, v]) => `T${k}=${v}`).join('  ')}`,
  '',
  '## Files',
  '',
  '```',
  `${OUT}/`,
  '├── tex/<flat>.tex   pristine texture. DO NOT EDIT. tex_android.py encode reads',
  '│                   its 40-byte header and geometry; it is also the pristine',
  '│                   reference for tex_clean_remainders.py',
  '├── png/<flat>.png   editable. Edit this, keep the same pixel dimensions',
  '└── worklist.csv     flat name -> pack, arc, entry name',
  '```',
  '',
  '## Loop',
  '',
  '```bash',
  'OUT=' + OUT,
  '',
  '# 1. edit OUT/png/<flat>.png (same dimensions, RGBA PNG)',
  '# 2. clean any half-erased remnants of the Japanese outline',
  'python3 tools-js/tex_clean_remainders.py $OUT/tex/<flat>.tex $OUT/png/<flat>.png',
  '',
  '# 3. re-encode',
  'python3 tools-js/tex_android.py encode $OUT/tex/<flat>.tex $OUT/png/<flat>.png $OUT/png/<flat>.new.tex',
  '```',
  '',
  'Then group the `.new.tex` files by the `arc` column and apply them with',
  '`arc-edit.cjs` + `fpk-pull.cjs`. One arc-edit per texture, all targeting the',
  'arc named in the manifest, then a single fpk-push per pack.',
  '',
  '## Constraints',
  '',
  '- 4 bits per channel: colours snap to multiples of 17 (0, 17, 34 ... 255).',
  '- Alpha is 4 bits too (16 levels). Block text out at **100% opacity** — a',
  '  faded fill leaves semi-transparent outline remnants that show up as dark',
  '  ghosts in-game. `tex_clean_remainders.py` fixes them afterwards.',
  '- Dimensions must not change: `encode` refuses a differently-sized image.',
  '- Text boxes are baked into the art, so keep replacements short enough to',
  '  fit the box the Japanese occupied.',
  '',
  '## Contents',
  '',
  ...arcs.map(([arc, list]) => `**\`${arc}\`** (${list.length})`), '',
  ...arcs.flatMap(([arc, list]) => list.map((r) => `- \`${r.flat}.png\` — ${r.width}x${r.height}`)),
  '',
].join('\n');
fs.writeFileSync(path.join(OUT, 'README.md'), readme);

console.log(`staged ${rows.length} textures into ${OUT}/`);
console.log(`  tex: ${rows.length}   png: ${rows.length}   csv rows: ${rows.length}`);
console.log(`  total ${(totalBytes / 1048576).toFixed(1)} MiB`);
console.log(`  by tier: ${Object.entries(byTier).sort().map(([k, v]) => `T${k}=${v}`).join('  ')}`);
console.log(`  arcs touched: ${arcs.length}`);
for (const [arc, list] of arcs) console.log(`    ${String(list.length).padStart(3)}  ${arc}`);
if (missingTex) console.log(`  WARNING: ${missingTex} rows had no .tex on disk`);
if (missingPng) console.log(`  WARNING: ${missingPng} rows had no .png on disk`);