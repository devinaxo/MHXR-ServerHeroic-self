/*
 * Builds src/json/evolve-costs.json from the game's own master data.
 *
 * Source: rsdnt_equip.arc :: tuning/xml/equip/evolve_equip
 *
 * Each row says:
 *   mEvolvePrepareHash   the piece that can be evolved (mst_equipment_id)
 *   mEvolveAfterHash     the piece it becomes
 *   mNeedZeny            zenny cost
 *   mEvolveAfterLevel    the level the result starts at
 *   mNeedItemHashList    up to 4 requirements (item or equipment master id)
 *   mNeedItemValueList   item: amount. equipment: minimum plus value.
 *
 * Equipment requirements are recognised by the hash being one of the equipment
 * ids in src/json/upgrade-costs.json; anything else is a material id from
 * item_material. Rows whose prepare piece is not a player equipment (otomo
 * gear and similar) are skipped.
 *
 * Run: node tools-js/build-evolve-costs.cjs
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'tools-js');
const OUT = path.join(ROOT, 'src/json/evolve-costs.json');
const COSTS = path.join(ROOT, 'src/json/upgrade-costs.json');

const ARCHIVE = path.join(SRC, 'rsdnt_equip.arc');
const TABLE = 'evolve_equip';

function main() {
  const { parseXfs } = require('./xfs-parse.cjs');
  const { Blowfish } = require('egoroof-blowfish');
  const zlib = require('node:zlib');
  const KEY = 'kaseoa nkaeka;eawf3';

  const unscramble = (buf) => {
    const out = Buffer.alloc(buf.length);
    for (let i = 0; i + 3 < buf.length; i += 4) {
      out[i] = buf[i + 3];
      out[i + 1] = buf[i + 2];
      out[i + 2] = buf[i + 1];
      out[i + 3] = buf[i];
    }
    const rest = buf.length % 4;
    if (rest > 0) buf.copy(out, buf.length - rest, buf.length - rest);
    return out;
  };

  const decode = (buf) => {
    const bf = new Blowfish(KEY, Blowfish.MODE.ECB, Blowfish.PADDING.NULL);
    const scrambled = unscramble(buf);
    let plain = Buffer.from(bf.decode(scrambled, Blowfish.TYPE.UINT8_ARRAY));
    if (plain.length < scrambled.length) {
      plain = Buffer.concat([plain, Buffer.alloc(scrambled.length - plain.length)]);
    }
    return unscramble(plain);
  };

  const readTable = (archivePath, wanted) => {
    const raw = fs.readFileSync(archivePath);
    const body = decode(raw.subarray(8));
    const count = raw.readUInt16LE(6);
    for (let i = 0; i < count; i++) {
      const entry = i * 80;
      const name = body
        .subarray(entry, entry + 64)
        .toString('utf8')
        .replace(/\0.*$/, '')
        .split('\\')
        .pop();
      if (name !== wanted) continue;
      const size = body.readUInt32LE(entry + 68);
      const start = body.readUInt32LE(entry + 76) - 8;
      return parseXfs(zlib.inflateSync(body.subarray(start, start + size)));
    }
    throw new Error(`${wanted} not found in ${path.basename(archivePath)}`);
  };

  const equipment = JSON.parse(fs.readFileSync(COSTS, 'utf8')).equipment;
  const rows = readTable(ARCHIVE, TABLE).root.mDataList.mpArray;

  const byEquipment = {};
  let skipped = 0;
  for (const row of rows) {
    const prepare = Number(row.mEvolvePrepareHash);
    const after = Number(row.mEvolveAfterHash);
    if (!equipment[String(prepare)] || !equipment[String(after)]) {
      skipped++;
      continue;
    }

    const materials = [];
    const equipments = [];
    const hashes = row.mNeedItemHashList || [];
    const values = row.mNeedItemValueList || [];
    for (let i = 0; i < hashes.length; i++) {
      const hash = Number(hashes[i]);
      const value = Number(values[i] ?? 0);
      if (!hash || value <= 0) continue;
      if (equipment[String(hash)]) {
        // One piece of that master id, at least `value` plus value.
        equipments.push({ mst_equipment_id: hash, minPotential: value });
      } else {
        materials.push({ mst_material_id: hash, amount: value });
      }
    }

    byEquipment[String(prepare)] = {
      name: equipment[String(prepare)].name,
      after,
      afterName: equipment[String(after)].name,
      zeny: Number(row.mNeedZeny ?? 0),
      afterLevel: Number(row.mEvolveAfterLevel ?? 0),
      materials,
      equipments,
    };
  }

  const out = {
    _comment:
      'Generated by tools-js/build-evolve-costs.cjs from rsdnt_equip.arc :: evolve_equip. ' +
      'Do not edit by hand.',
    _note:
      'equipments[].minPotential is the minimum plus value (potential) the sacrificed piece must have. ' +
      'materials[].amount is the item count.',
    byEquipment,
  };

  fs.writeFileSync(OUT, JSON.stringify(out, null, 1));
  console.log(
    `wrote ${OUT}: ${Object.keys(byEquipment).length} evolutions, ${skipped} rows skipped ` +
      '(prepare or result outside the player equipment table)',
  );
}

main();
